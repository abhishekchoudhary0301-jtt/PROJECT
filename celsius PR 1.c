#include<stdio.h>
int main()
{
	float celsius,fahrenheit;
	printf("temperature of celsius");
	scanf("%f",&celsius);
	fahrenheit=(9.0/5.0*celsius)+32.0;
	printf("the temperature in fahrenheit:%f\n",fahrenheit);
	return 0;

	
	
}
